"""Orchestrates the pipeline: read task -> resolve inputs -> summarize -> prompt ->
generate -> execute -> self-check -> (at most one repair) -> execute -> self-check -> trace.

task_dir and out_dir are opaque parameters handed in by the CLI -- never hardcoded to /input or
/app/output or /output.
"""

from __future__ import annotations

import shutil
import tempfile
import time
from pathlib import Path

from agent.executor import run_generated_code
from agent.generation import generate_script
from agent.input_resolver import resolve_inputs
from agent.model_client import ModelClient
from agent.prompt import build_messages, build_repair_messages
from agent.self_check import self_check
from agent.summarizer import summarize
from agent.task_reader import read_task
from agent.trace import Trace

_DEFAULT_TIMEOUT_SEC = 1800.0
_LOG_PREVIEW_CHARS = 4000

# --- Per-unit time budget -------------------------------------------------------------------------
# The card's [agent].timeout_sec is the platform's ceiling for the WHOLE container: image pull, every
# model call and every generated-code run share it, and the container is killed when it is reached.
# Handing the full value to each generated-code run therefore lets one hung script take the entire unit,
# leaving no time for self-check or repair, and lets a late repair be cut off mid-write by the platform
# (no rollback can run once the process is killed). One absolute deadline for the unit fixes both:
#   * _RESERVE_FRACTION: our own deadline is this much BEFORE the ceiling, so a timed-out repair is
#     rolled back by us instead of being killed by the platform (and covers the unknown pull time).
#   * _FIRST_RUN_FRACTION: the first run may use at most this share of the usable budget, so a
#     runaway script leaves the rest for the one repair. Trade-off: a legitimate first script that
#     needs more than that share (45% of the ceiling) is killed and must be regenerated by the repair.
#   * _MIN_REPAIR_WINDOW_SEC: a repair is only started (and its script only run) with at least this
#     much budget left; the repair run then gets everything that remains.
# The deadline is absolute, so time spent in model calls is automatically not given out twice.
_RESERVE_FRACTION = 0.10
_FIRST_RUN_FRACTION = 0.5
_MIN_REPAIR_WINDOW_SEC = 120.0


def _now() -> float:
    return time.monotonic()


def _copy_dir_contents(src: Path, dst: Path) -> None:
    """Copy everything under src into dst (which must exist), keeping src itself in place."""
    shutil.copytree(src, dst, symlinks=True, dirs_exist_ok=True)


def _clear_dir(directory: Path) -> None:
    """Delete everything inside `directory` but not the directory itself: out_dir is a bind
    mount, so only its contents can be removed."""
    for entry in directory.iterdir():
        if entry.is_dir() and not entry.is_symlink():
            shutil.rmtree(entry)
        else:
            entry.unlink()


def solve(task_dir: str | Path, out_dir: str | Path) -> None:
    started = _now()
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    trace = Trace()

    # A broken/unreadable task bundle is a real infra problem -- nothing meaningful can be
    # attempted without it, so this is allowed to raise and crash the process.
    bundle = read_task(task_dir)
    resolved_inputs = resolve_inputs(bundle.task_dir, bundle.manifest)
    summaries = [summarize(r, bundle.instruction_text) for r in resolved_inputs]
    ceiling_sec = float(bundle.card.get("agent", {}).get("timeout_sec", _DEFAULT_TIMEOUT_SEC))
    deadline = started + ceiling_sec * (1.0 - _RESERVE_FRACTION)
    first_run_cap_sec = (deadline - started) * _FIRST_RUN_FRACTION

    messages = build_messages(bundle.instruction_text, resolved_inputs, summaries, out_dir)
    try:
        client = ModelClient()
        script = generate_script(client, messages, deadline=deadline, now=_now)
        code = script.code
    except Exception as exc:  # noqa: BLE001 - see below
        # Without the model there is no first attempt, and a placeholder deliverable would be a
        # fabricated answer, so nothing is written. The official Track 1 guidance is that an uncaught
        # exception forfeits the unit's gates and that the process should still exit 0: the checker
        # scores the missing output as zero either way, and the failure stays visible in the trace.
        trace.record("initial_generation_failed", error=f"{type(exc).__name__}: {exc}")
        trace.log_summary()
        return
    trace.record("initial_generation", code=code, **script.trace_fields())

    first_run_timeout = max(1.0, min(first_run_cap_sec, deadline - _now()))
    result = run_generated_code(code, out_dir, timeout_sec=first_run_timeout)
    trace.record("execution", exit_code=result.exit_code, timed_out=result.timed_out, stderr=result.stderr)

    check = self_check(bundle, resolved_inputs, summaries, out_dir, result)
    trace.record("self_check", passed=check.passed, outcomes=[o.__dict__ for o in check.outcomes])

    repair_script = None
    if not check.passed:
        # The repair is a bonus attempt, never a risk to what the first attempt already left in
        # out_dir. If it cannot be obtained (the model call raises), or its script crashes, the
        # first attempt's artifact stands and this process still exits 0 like any other
        # downstream failure -- the checker scores whatever is on disk.
        remaining = deadline - _now()
        if remaining < _MIN_REPAIR_WINDOW_SEC:
            trace.record(
                "repair_skipped",
                reason="too little unit budget left to start a repair",
                remaining_sec=round(remaining, 1),
            )
        else:
            try:
                repair_messages = build_repair_messages(
                    bundle.instruction_text,
                    resolved_inputs,
                    summaries,
                    out_dir,
                    previous_code=code,
                    execution_result=result,
                    self_check_result=check,
                )
                repair_script = generate_script(client, repair_messages, deadline=deadline, now=_now)
            except Exception as exc:  # noqa: BLE001 - any failure here must leave the artifact alone
                trace.record("repair_generation_failed", error=f"{type(exc).__name__}: {exc}")

    if repair_script is not None:
        repair_run_timeout = deadline - _now()
        if repair_run_timeout < _MIN_REPAIR_WINDOW_SEC:
            # The repair request itself used up the window: do not start a run the platform would
            # have to cut off mid-write. The first attempt's artifact stands.
            trace.record(
                "repair_skipped",
                reason="the repair request used up the unit budget",
                remaining_sec=round(repair_run_timeout, 1),
            )
        else:
            code = repair_script.code
            trace.record("repair_generation", code=code, **repair_script.trace_fields())

            first_result, first_check = result, check
            # Only a first attempt that ran to completion is an artifact worth protecting.
            first_attempt_ran = result.exit_code == 0 and not result.timed_out
            with tempfile.TemporaryDirectory(prefix="t1-agent-first-attempt-") as backup:
                if first_attempt_ran:
                    _copy_dir_contents(out_dir, Path(backup))

                result = run_generated_code(code, out_dir, timeout_sec=repair_run_timeout)
                if first_attempt_ran and (result.timed_out or result.exit_code != 0):
                    _clear_dir(out_dir)
                    _copy_dir_contents(Path(backup), out_dir)
                    trace.record(
                        "repair_discarded",
                        reason="repair run failed; first attempt's output restored",
                        exit_code=result.exit_code,
                        timed_out=result.timed_out,
                    )
                    result, check = first_result, first_check
                else:
                    check = self_check(bundle, resolved_inputs, summaries, out_dir, result)

    # "final_execution"/"final_self_check" are recorded unconditionally -- when no repair ran (or a
    # failed repair was discarded), this repeats the same result as "execution"/"self_check"
    # above, which is intentional: the trace always has all six named stages in order, whether or
    # not a repair happened. A failed or skipped repair adds "repair_generation_failed",
    # "repair_skipped" or "repair_discarded" between them. (An initial-generation failure returns
    # earlier with only "initial_generation_failed".)
    trace.record("final_execution", exit_code=result.exit_code, timed_out=result.timed_out, stderr=result.stderr)
    trace.record("final_self_check", passed=check.passed, outcomes=[o.__dict__ for o in check.outcomes])

    # A failing/erroring generated program is not this wrapper's failure: the checker's own gates
    # will correctly score a missing/wrong deliverable. Log for local debugging and exit 0
    # regardless.
    trace.log_summary()
